import java.util.Scanner.*;
public class Month{
public static void main(String[] args){
Scanner scan=new Scanner(System.in);
int a=scan.nextInt();
switch(a){
case 1:
System.out.println("January");
case 2:
System.out.println("feb");
break;
case 3:
System.out.println("mar");
break;
default:
System.out.println("Invalid");
}
}
}


